import { writeFile } from 'node:fs/promises';
import { createPricingCatalogue } from '../shared/pricingCatalogue.js';

const enabled = process.env.WEBSITE_PRICEBOOK_ENABLED === 'true';
const destination = new URL('../shared/publishedPricebookSnapshot.js', import.meta.url);
let snapshot = { id: 'bundled', version: 'bundled', overrides: {} };
if (enabled) {
  const source = process.env.WEBSITE_PRICEBOOK_SOURCE_URL;
  if (!source || !source.startsWith('https://')) throw new Error('WEBSITE_PRICEBOOK_SOURCE_URL must be the HTTPS public pricebook endpoint before building with managed prices.');
  const response = await fetch(source, { signal: AbortSignal.timeout(15000), cache: 'no-store', headers: { Accept: 'application/json' } });
  if (!response.ok) throw new Error(`Could not load published website prices (${response.status}); build stopped to avoid stale prices.`);
  const data = await response.json();
  if (!data || typeof data.id !== 'string' || !data.id || !data.overrides || typeof data.overrides !== 'object') throw new Error('Published pricebook response is invalid.');
  createPricingCatalogue(data.overrides);
  snapshot = { id: data.id, version: data.version || data.id, overrides: data.overrides };
}
await writeFile(destination, `// Generated by scripts/sync-website-pricebook.mjs. Never include private data.\nexport default ${JSON.stringify(snapshot, null, 2)};\n`, 'utf8');
console.log(`[website-pricebook] Build snapshot: ${snapshot.version}${enabled ? '' : ' (managed prices disabled)'}`);
